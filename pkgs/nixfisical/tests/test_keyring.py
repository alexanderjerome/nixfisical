"""Tests for the keyring: the age key's round trip into Infisical and back.

Two failure modes are worth a suite here, and neither is a crash.

The first is storing something that is not the key. A truncated paste, an SSH
private key, the public half by mistake -- all of them upload cleanly, all of
them look right in the UI, and all of them are discovered at the next
activation of whichever host pulled them. So the checksum path is tested
against real ``age-keygen`` output rather than against a round trip through
this module's own encoder, which would only prove it agrees with itself.

The second is a successful run that quietly widens who can read the key: an
overwrite that strands every host already holding the old one, a group grant
that hands the estate's master key to a team, an install path that points
somewhere the host was using for something else.

Everything is offline. The key vectors below were generated by ``age-keygen``
for this file and have never encrypted anything.
"""

