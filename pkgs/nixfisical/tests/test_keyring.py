def test_install_dry_run_writes_nothing(tmp_path: Path) -> None:
    destination = tmp_path / "key.txt"
    client = FakeClient(
        projects={"keyring": "k1"},
        secrets=[
            stored("/fleet", KEY_SECRET, KEY_FILE_A),
            stored("/fleet", KEY_PATH, str(destination)),
        ],
    )
    summary = install(client, name="fleet", organization_id="org", dry_run=True)
    assert summary.ok
    assert not destination.exists()


def test_install_surfaces_an_api_failure(tmp_path: Path) -> None:
    class Broken(FakeClient):
        def list_secrets(self, **_: Any):
            raise InfisicalError("503 from the instance")

    summary = install(
        Broken(projects={"keyring": "k1"}), name="fleet", organization_id="org"
    )
    assert not summary.ok
    assert "503" in " ".join(summary.errors)


def test_install_ignores_other_entries_in_the_same_project(tmp_path: Path) -> None:
    """One project holds several keyrings; the folder is what selects one."""
    destination = tmp_path / "key.txt"
    client = FakeClient(
        projects={"keyring": "k1"},
        secrets=[
            stored("/other", KEY_SECRET, f"{SECRET_B}\n"),
            stored("/other", KEY_PATH, "/should/not/be/used"),
            stored("/fleet", KEY_SECRET, KEY_FILE_A),
            *placement_at(destination),
        ],
    )
    summary = install(client, name="fleet", organization_id="org")
    assert summary.ok, summary.errors
    assert destination.read_text() == KEY_FILE_A


